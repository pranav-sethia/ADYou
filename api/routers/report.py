"""
API Router for generating ADU feasibility reports using Gemini 2.5 Flash.
"""
from __future__ import annotations

import os
from pathlib import Path

from fastapi import APIRouter, HTTPException
from pydantic import BaseModel, Field

from agents import Agent, Runner, set_tracing_disabled
from agents.extensions.models.litellm_model import LitellmModel

set_tracing_disabled(True)

router = APIRouter()

repo_root = Path(__file__).resolve().parent.parent.parent


def _get_secret(name: str) -> str | None:
    value = os.environ.get(name)
    if value and value.strip():
        return value.strip()
    env_file = repo_root / ".env"
    if env_file.exists():
        try:
            for line in env_file.read_text(encoding="utf-8").splitlines():
                line = line.strip()
                if not line or line.startswith("#") or "=" not in line:
                    continue
                k, v = line.split("=", 1)
                if k.strip() == name and v.strip():
                    return v.strip().strip('"').strip("'")
        except Exception:
            pass
    return None


# ── Request / Response models ───────────────────────────────────────────────

class HistoryMessage(BaseModel):
    role: str
    content: str


class ReportRequest(BaseModel):
    messages: list[HistoryMessage] = Field(default_factory=list)
    address: str | None = None
    adu_sqft: float | None = None
    adu_shape: str | None = None
    adu_type: str | None = None
    primary_use: str | None = None
    blocker_types: list[str] = Field(default_factory=list)
    property_area: float | None = None
    buildable_area: float | None = None
    setback: float | None = None
    max_adu_sqft: float | None = None


class ReportResponse(BaseModel):
    report: str  # Markdown report


# ── Endpoint ────────────────────────────────────────────────────────────────

REPORT_SYSTEM_PROMPT = """\
You are a professional ADU (Accessory Dwelling Unit) feasibility report writer.

Given a conversation between a homeowner and an ADU advisor, plus property 
analysis data, produce a concise, well-structured feasibility report in Markdown.

Use the following structure exactly:

# ADU Feasibility Report

## Executive Summary
2-3 sentences summarising whether the project is feasible and the key takeaway.

## Property Overview
| Field | Value |
|-------|-------|
(Fill in address, lot size, buildable area, setback, max ADU, planned ADU size, ADU type, shape)

## Zoning & Regulatory Analysis
Bullet points covering setback rules, California HCD guidelines, and any 
blockers the user mentioned (HOA, historic district, hillside, etc.).

## Financial Snapshot
Rough cost range, intended use (rental / family / personal), and any 
relevant financial notes from the conversation.
Generate an estimated cost range for the rental price of the ADU. You MUST generate a range.
Generate an estimated cost range for the construction of the ADU. You MUST generate a range.

## Recommendations & Next Steps
3-5 actionable bullet points for the homeowner.

---
*Report generated by ADU Base AI — powered by the California HCD Handbook.*

IMPORTANT: Keep the report professional, concise, and actionable. Use the 
conversation history for qualitative context and the property data for 
quantitative facts. Do NOT invent numbers — only use what is provided.
"""


@router.post("/generate-report", response_model=ReportResponse)
async def generate_report(req: ReportRequest) -> ReportResponse:
    api_key = _get_secret("GEMINI_API_KEY")
    if not api_key:
        raise HTTPException(status_code=503, detail="GEMINI_API_KEY not set.")

    # Build the context payload for the agent
    parts: list[str] = []

    # Property context
    ctx_lines: list[str] = []
    if req.address:
        ctx_lines.append(f"- Address: {req.address}")
    if req.property_area:
        ctx_lines.append(f"- Property Area: {req.property_area:,.0f} sq ft")
    if req.buildable_area:
        ctx_lines.append(f"- Buildable Area: {req.buildable_area:,.0f} sq ft")
    if req.setback:
        ctx_lines.append(f"- Setback: {req.setback} ft")
    if req.max_adu_sqft:
        ctx_lines.append(f"- Max ADU Allowed: {req.max_adu_sqft:,.0f} sq ft")
    if req.adu_sqft:
        ctx_lines.append(f"- Planned ADU Size: {req.adu_sqft:,.0f} sq ft")
    if req.adu_type:
        ctx_lines.append(f"- ADU Type: {req.adu_type.replace('_', ' ').title()}")
    if req.adu_shape:
        ctx_lines.append(f"- ADU Shape: {req.adu_shape.replace('_', ' ').title()}")
    if req.primary_use:
        ctx_lines.append(f"- Primary Use: {req.primary_use}")
    if req.blocker_types:
        ctx_lines.append(f"- Potential Blockers: {', '.join(req.blocker_types)}")

    if ctx_lines:
        parts.append("**Property Analysis Data:**\n" + "\n".join(ctx_lines))

    # Conversation history
    if req.messages:
        convo = "\n".join(
            f"{'User' if m.role == 'user' else 'Advisor'}: {m.content}"
            for m in req.messages[-30:]  # Keep last 30 messages
        )
        parts.append(f"**Advisor Conversation:**\n{convo}")

    user_input = "\n\n".join(parts) if parts else "Generate a generic ADU feasibility report."

    agent = Agent(
        name="Report Writer",
        instructions=REPORT_SYSTEM_PROMPT,
        model=LitellmModel(model="gemini/gemini-2.5-flash", api_key=api_key),
    )

    try:
        result = await Runner.run(agent, input=user_input)
        report_md = result.final_output.strip()
    except Exception as exc:
        raise HTTPException(
            status_code=502, detail=f"Report generation failed: {exc}"
        ) from exc

    return ReportResponse(report=report_md)


# ── Report to Listing Parsing ───────────────────────────────────────────────

class ParseReportRequest(BaseModel):
    report_markdown: str


class ParsedListingData(BaseModel):
    address: str = Field(description="The property street address, if found, without city or state.")
    city: str = Field(description="The city of the property, if found.")
    zipCode: str = Field(description="The zip code of the property, if found.")
    bedrooms: int = Field(description="The estimated number of bedrooms for the ADU.")
    bathrooms: float = Field(description="The estimated number of bathrooms for the ADU (e.g. 1, 1.5).")
    sqft: int = Field(description="The planned or maximum allowed square footage for the ADU.")
    monthlyRent: int = Field(description="A conservative single number estimate for the monthly rental price of the ADU. If a range is given, pick the lower end.")
    description: str = Field(description="A compelling, 2-3 paragraph marketplace listing description written to attract potential tenants to this newly built ADU.")


PARSE_SYSTEM_PROMPT = """\
You are an expert real estate data extractor and copywriter.
Given an ADU Feasibility Report, your job is to extract the basic property facts AND 
write a compelling, enthusiastic rental listing description based on the proposed ADU.

If any specific data (like address or exact rent) is missing, make a logical guess 
or use standard defaults (e.g. 1 bed, 1 bath). 
Always return standard types (ints for sqft/rent, floats for baths).

You MUST respond strictly with a valid JSON object matching this schema:
{
    "address": "string",
    "city": "string",
    "zipCode": "string",
    "bedrooms": number,
    "bathrooms": number,
    "sqft": number,
    "monthlyRent": number,
    "description": "string"
}
Do not include any other text or markdown block formatting. Just the JSON.
"""


@router.post("/parse-report-to-listing", response_model=ParsedListingData)
async def parse_report_to_listing(req: ParseReportRequest) -> ParsedListingData:
    api_key = _get_secret("GEMINI_API_KEY")
    if not api_key:
        raise HTTPException(status_code=503, detail="GEMINI_API_KEY not set.")

    agent = Agent(
        name="Listing Extractor",
        instructions=PARSE_SYSTEM_PROMPT,
        model=LitellmModel(
            model="gemini/gemini-2.5-flash", 
            api_key=api_key,
        ),
    )

    try:
        user_input = f"**Feasibility Report:**\n{req.report_markdown}"
        result = await Runner.run(agent, input=user_input)
        
        # LitellmModel with prompt-driven structured output
        import json
        import re
        output_text = result.final_output.strip()
        # Clean markdown code block if present
        output_text = re.sub(r'^```json\s*', '', output_text)
        output_text = re.sub(r'\s*```$', '', output_text)
        
        structured_data = json.loads(output_text)
        return ParsedListingData(**structured_data)
        
    except Exception as exc:
        raise HTTPException(
            status_code=502, detail=f"Listing extraction failed: {exc}"
        ) from exc
